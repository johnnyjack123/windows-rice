// Downloads Material Symbols subset fonts (Rounded, Sharp, Outlined) that
// contain exactly the icons listed in web/src/design/icons.json, so the app
// works offline. Run after changing the icon list: `pnpm icons`.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(new URL('../package.json', import.meta.url)));
const listFile = path.join(root, 'web/src/design/icons.json');
const outDir = path.join(root, 'web/src/design/fonts');
const STYLES = ['Rounded', 'Sharp', 'Outlined'];
const AXES = 'opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200';
// Google Fonts only serves woff2 to modern browsers.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36';

const names = [...new Set(JSON.parse(await readFile(listFile, 'utf8')))].sort();
const families = STYLES.map((s) => `family=Material+Symbols+${s}:${AXES}`).join('&');
const url = `https://fonts.googleapis.com/css2?${families}&icon_names=${names.join(',')}&display=block`;

const res = await fetch(url, { headers: { 'User-Agent': UA } });
if (!res.ok) {
  throw new Error(`Google Fonts returned ${res.status}. Is every name in icons.json a valid Material Symbol?\n${await res.text()}`);
}
const css = await res.text();
await mkdir(outDir, { recursive: true });

const faces = [];
for (const block of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
  const family = /font-family:\s*'([^']+)'/.exec(block[1])?.[1];
  const src = /src:\s*url\(([^)]+)\)/.exec(block[1])?.[1];
  if (!family || !src) {
    continue;
  }
  const file = `${family.toLowerCase().replace(/\s+/g, '-')}.woff2`;
  const font = await fetch(src, { headers: { 'User-Agent': UA } });
  await writeFile(path.join(outDir, file), Buffer.from(await font.arrayBuffer()));
  faces.push(`@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: 100 700;
  font-display: block;
  src: url('./${file}') format('woff2');
}`);
  console.log(`saved ${file}`);
}

if (faces.length !== STYLES.length) {
  throw new Error(`expected ${STYLES.length} font faces, got ${faces.length}`);
}
await writeFile(
  path.join(outDir, 'material-symbols.css'),
  `/* Generated by scripts/fetch-icons.mjs — do not edit. ${names.length} icons. */\n${faces.join('\n')}\n`,
);
console.log(`${names.length} icons, ${faces.length} styles`);
